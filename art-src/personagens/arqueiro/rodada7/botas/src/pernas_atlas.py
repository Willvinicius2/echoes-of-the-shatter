def uvmap(rect, u, t):
    """(u,t) em [0,1] (t=0 embaixo do retangulo) -> UV do glTF/Blender (origem embaixo)."""
    x0, y0, x1, y1 = rect
    x = x0 + u * (x1 - x0)
    y = y1 - t * (y1 - y0)
    return (x / TAM, 1.0 - y / TAM)


